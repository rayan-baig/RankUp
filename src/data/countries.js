/** The flag emoji for a two-letter code: two regional-indicator letters. */
export function countryFlag(code) {
  if (!/^[A-Z]{2}$/.test(String(code || ''))) return '🏳️'
  return String.fromCodePoint(...[...code].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65))
}

let names = null
/** The country's name in the phone's language, or the code if the phone cannot say. */
export function countryName(code) {
  try {
    names = names || new Intl.DisplayNames([typeof navigator !== 'undefined' ? navigator.language : 'en', 'en'], { type: 'region' })
    return names.of(code) || code
  } catch {
    return code
  }
}

/** Every country, sorted by its name, for a picker. */
export function countryOptions() {
  return COUNTRY_CODES.map((code) => ({ code, name: countryName(code), flag: countryFlag(code) }))
    .sort((a, b) => a.name.localeCompare(b.name))
}
